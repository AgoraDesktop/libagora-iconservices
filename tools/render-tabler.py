#!/usr/bin/env python3
"""Render the vendored Tabler symbols into the sizes this tree's themes ship.

    render-tabler.py <icons-dir> <theme-dir> [sizes]

`<icons-dir>` is a checkout's `icons/outline/` (the SVGs), `<theme-dir>` is `themes/Tabler`, and `sizes` is a
comma-separated list of pixel sizes — 24,48,96 by default, which is the design size of a Tabler symbol and the
two multiples a 1×/2× desktop needs.

Every PNG is black ink on transparency: Tabler draws its outlines with `stroke="currentColor"`, which `rsvg-convert`
resolves to black, and that is exactly what a *template* image has to be — the drawing side inks it, so a disabled
button's symbol is the same grey as its label.

THE OUTPUT IS COMMITTED, NOT GENERATED BY A BUILD. Art produced by a build step is a property of HOW a project was
built: Forge built by Forge once shipped the drawn fallback while the checkout's build shipped Tabler's, because the
generated build ran none of the component's rules. So this script is the RECIPE and the pixels live in the repository —
see `themes/Tabler/PROVENANCE.md`. It is deterministic for a given librsvg, so regenerating an unchanged set is a no-op.

Why a script at all: 5,203 symbols × 3 sizes is 15,609 `rsvg-convert` calls, and doing them by hand is how a theme ends
up with three files from a different upstream snapshot.
"""

import os
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor


def render_one(job):
    rsvg, svg, theme, sizes = job
    name = os.path.splitext(os.path.basename(svg))[0]
    for size in sizes:
        out_dir = os.path.join(theme, f"{size}x{size}", "actions")
        subprocess.run([rsvg, "-w", str(size), "-h", str(size), svg,
                        "-o", os.path.join(out_dir, name + ".png")], check=True)
    return name


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        return 2
    icons_dir, theme_dir = sys.argv[1], sys.argv[2]
    sizes = [int(s) for s in (sys.argv[3] if len(sys.argv) > 3 else "24,48,96").split(",") if s.strip()]
    rsvg = os.environ.get("RSVG_CONVERT", "rsvg-convert")

    svgs = sorted(os.path.join(icons_dir, f) for f in os.listdir(icons_dir) if f.endswith(".svg"))
    if not svgs:
        print(f"no SVGs in {icons_dir}", file=sys.stderr)
        return 1
    for size in sizes:
        os.makedirs(os.path.join(theme_dir, f"{size}x{size}", "actions"), exist_ok=True)

    jobs = [(rsvg, svg, theme_dir, sizes) for svg in svgs]
    with ThreadPoolExecutor(max_workers=os.cpu_count() or 4) as pool:
        done = list(pool.map(render_one, jobs))

    print(f"{len(done)} symbols × {len(sizes)} sizes into {theme_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
